using System.CommandLine.Invocation;

namespace System.CommandLine.Help
{
    /// <summary>
    /// Provides command-line help.
    /// </summary>
    public sealed class HelpAction : SynchronousCommandLineAction
    {
        private HelpBuilder? _builder;
        private int _maxWidth = -1;

        /// <summary>
        /// Gets or sets the maximum width in characters after which help output is wrapped.
        /// </summary>
        /// <value>The maximum width in characters after which help output is wrapped. The default is <see cref="Console.WindowWidth"/>.</value>
        public int MaxWidth
        {
            get
            {
                if (_maxWidth < 0)
                {
                    try
                    {
                        _maxWidth = Console.IsOutputRedirected ? int.MaxValue : Console.WindowWidth;
                    }
                    catch (Exception)
                    {
                        _maxWidth = int.MaxValue;
                    }
                }

                return _maxWidth;
            }
            set
            {
                if (value <= 0)
                {
                    throw new ArgumentOutOfRangeException(nameof(value));
                }

                _maxWidth = value;
            }
        }

        /// <summary>
        /// Gets or sets the <see cref="Builder"/> to use to format help output.
        /// </summary>
        internal HelpBuilder Builder
        {
            get => _builder ??= new HelpBuilder(MaxWidth);
            set => _builder = value ?? throw new ArgumentNullException(nameof(value));
        }

        /// <summary>
        /// Gets or sets a predicate that projects the symbol tree onto a visibility-filtered help view,
        /// typically based on the caller's authorization set. Symbols rejected by the predicate contribute
        /// no aliases, usage lines, or default values to the output. When <see langword="null"/>, symbols
        /// are shown unless <see cref="Symbol.Hidden"/> is <see langword="true"/>.
        /// </summary>
        /// <remarks>
        /// The projection applies only to the help output generated by this action. It never modifies
        /// <see cref="Symbol.Hidden"/>, so the parse tree keeps recognizing the full, original command
        /// tree and concurrent help requests are unaffected.
        /// </remarks>
        public Func<Symbol, bool>? SymbolVisibility { get; set; }

        /// <inheritdoc />
        public override int Invoke(ParseResult parseResult)
        {
            var output = parseResult.InvocationConfiguration.Output;

            var helpContext = new HelpContext(Builder,
                                              parseResult.CommandResult.Command,
                                              output,
                                              SymbolVisibility);

            Builder.Write(helpContext);

            return 0;
        }

        public override bool ClearsParseErrors => true;
    }
}
